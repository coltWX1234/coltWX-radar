-- COLTWX RADAR v0.2 social + public chat schema
-- Run in Supabase SQL Editor. Keep email confirmation enabled.
create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique not null check (char_length(username) between 3 and 24),
  display_name text default '',
  bio text default '',
  avatar_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.posts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 2000),
  created_at timestamptz not null default now()
);
create table if not exists public.chat_rooms (
  id bigint generated by default as identity primary key,
  name text unique not null,
  description text not null default '',
  created_at timestamptz not null default now()
);
create table if not exists public.room_messages (
  id bigint generated by default as identity primary key,
  room_id bigint not null references public.chat_rooms(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1500),
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;
alter table public.posts enable row level security;
alter table public.chat_rooms enable row level security;
alter table public.room_messages enable row level security;

drop policy if exists "Profiles are viewable by everyone" on public.profiles;
create policy "Profiles are viewable by everyone" on public.profiles for select using (true);
drop policy if exists "Users insert their own profile" on public.profiles;
create policy "Users insert their own profile" on public.profiles for insert with check (auth.uid() = id);
drop policy if exists "Users update their own profile" on public.profiles;
create policy "Users update their own profile" on public.profiles for update using (auth.uid() = id);

drop policy if exists "Posts are viewable by everyone" on public.posts;
create policy "Posts are viewable by everyone" on public.posts for select using (true);
drop policy if exists "Signed-in users create their own posts" on public.posts;
create policy "Signed-in users create their own posts" on public.posts for insert with check (auth.uid() = user_id);
drop policy if exists "Authors can delete their own posts" on public.posts;
create policy "Authors can delete their own posts" on public.posts for delete using (auth.uid() = user_id);

drop policy if exists "Rooms are visible to everyone" on public.chat_rooms;
create policy "Rooms are visible to everyone" on public.chat_rooms for select using (true);
drop policy if exists "Signed-in users read room messages" on public.room_messages;
create policy "Signed-in users read room messages" on public.room_messages for select to authenticated using (true);
drop policy if exists "Users send messages as themselves" on public.room_messages;
create policy "Users send messages as themselves" on public.room_messages for insert to authenticated with check (auth.uid() = user_id);
drop policy if exists "Users delete own room messages" on public.room_messages;
create policy "Users delete own room messages" on public.room_messages for delete to authenticated using (auth.uid() = user_id);

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public as $$
declare chosen_username text;
begin
  chosen_username := coalesce(new.raw_user_meta_data->>'username', 'wx_' || substr(replace(new.id::text, '-', ''), 1, 12));
  insert into public.profiles (id, username, display_name)
  values (new.id, chosen_username, '');
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
for each row execute procedure public.handle_new_user();

