-- v0.3: private storm-chasing groups, group chat, and approximate expiring check-ins.
create table if not exists public.chase_groups (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 2 and 50),
  description text not null default '' check (char_length(description) <= 120),
  created_by uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);
create table if not exists public.chase_group_members (
  group_id bigint not null references public.chase_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'member' check (role in ('owner','member')),
  joined_at timestamptz not null default now(),
  primary key (group_id,user_id)
);
create table if not exists public.chase_group_messages (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.chase_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  body text not null check (char_length(body) between 1 and 1500),
  created_at timestamptz not null default now()
);
-- Deliberately stores only a user-entered approximate place label, never GPS coordinates.
create table if not exists public.chase_group_checkins (
  id bigint generated by default as identity primary key,
  group_id bigint not null references public.chase_groups(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  label text not null check (char_length(label) between 3 and 90),
  expires_at timestamptz not null,
  created_at timestamptz not null default now()
);

alter table public.chase_groups enable row level security;
alter table public.chase_group_members enable row level security;
alter table public.chase_group_messages enable row level security;
alter table public.chase_group_checkins enable row level security;

-- Group creator is automatically made the owner through this trigger.
create or replace function public.add_chase_group_owner()
returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.chase_group_members(group_id,user_id,role)
  values(new.id,new.created_by,'owner') on conflict do nothing;
  return new;
end;
$$;
drop trigger if exists on_chase_group_created on public.chase_groups;
create trigger on_chase_group_created after insert on public.chase_groups
for each row execute procedure public.add_chase_group_owner();

-- Only members can view group details, membership, messages, and check-ins.
drop policy if exists "Members can view their chase groups" on public.chase_groups;
create policy "Members can view their chase groups" on public.chase_groups for select to authenticated
using (exists(select 1 from public.chase_group_members m where m.group_id=id and m.user_id=auth.uid()));
drop policy if exists "Signed in users can create chase groups" on public.chase_groups;
create policy "Signed in users can create chase groups" on public.chase_groups for insert to authenticated
with check (auth.uid()=created_by);

drop policy if exists "Members can view group membership" on public.chase_group_members;
create policy "Members can view group membership" on public.chase_group_members for select to authenticated
using (user_id=auth.uid());
-- Membership changes are intentionally not exposed to clients in this starter.
-- The security-definer trigger adds the creator as owner. Invite/join flows will
-- be added with server-validated invite codes in a later version.

drop policy if exists "Group members read group messages" on public.chase_group_messages;
create policy "Group members read group messages" on public.chase_group_messages for select to authenticated
using (exists(select 1 from public.chase_group_members m where m.group_id=chase_group_messages.group_id and m.user_id=auth.uid()));
drop policy if exists "Group members send messages" on public.chase_group_messages;
create policy "Group members send messages" on public.chase_group_messages for insert to authenticated
with check (auth.uid()=user_id and exists(select 1 from public.chase_group_members m where m.group_id=chase_group_messages.group_id and m.user_id=auth.uid()));

drop policy if exists "Group members read temporary checkins" on public.chase_group_checkins;
create policy "Group members read temporary checkins" on public.chase_group_checkins for select to authenticated
using (exists(select 1 from public.chase_group_members m where m.group_id=chase_group_checkins.group_id and m.user_id=auth.uid()));
drop policy if exists "Members share their own temporary checkins" on public.chase_group_checkins;
create policy "Members share their own temporary checkins" on public.chase_group_checkins for insert to authenticated
with check (auth.uid()=user_id and expires_at > now() and expires_at <= now() + interval '8 hours'
  and exists(select 1 from public.chase_group_members m where m.group_id=chase_group_checkins.group_id and m.user_id=auth.uid()));
drop policy if exists "Members remove their own checkins" on public.chase_group_checkins;
create policy "Members remove their own checkins" on public.chase_group_checkins for delete to authenticated
using (auth.uid()=user_id);

